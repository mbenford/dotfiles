#!/usr/bin/env python3
"""Usage: svg2qml.py <icons_dir> <output.qml>"""

import json, re, sys
import xml.etree.ElementTree as ET
from pathlib import Path


def main(icons_dir, out_file):
    paths, viewboxes = {}, set()
    for svg in sorted(Path(icons_dir).glob("*.svg")):
        try:
            vb, d = parse(svg)
        except Exception as e:
            print(f"skip {svg.name}: {e}", file=sys.stderr)
            continue
        viewboxes.add(tuple(vb))
        paths[svg.stem] = d

    if len(viewboxes) != 1:
        sys.exit(f"viewBoxes differ across icons: {viewboxes}")

    entries = ",\n".join(
        f"		{json.dumps(k)}: {json.dumps(v)}" for k, v in paths.items()
    )
    Path(out_file).write_text(f"""// Generated by svg2qml.py - do not edit
pragma Singleton
import Quickshell

Singleton {{
	readonly property var viewBox: {json.dumps(list(viewboxes.pop()))}
	readonly property var paths: ({{
{entries}
	}})
}}
""")
    print(f"wrote {len(paths)} icons to {out_file}")


def parse(svg_file):
    root = ET.parse(svg_file).getroot()
    vb = [float(v) for v in re.split(r"[,\s]+", root.get("viewBox", "").strip())]
    # match <path> regardless of XML namespace; join multiple paths as subpaths
    ds = [el.get("d") for el in root.iter() if el.tag.endswith("path") and el.get("d")]
    if len(vb) != 4 or not ds:
        raise ValueError("missing viewBox or path data")
    return vb, " ".join(ds)


if __name__ == "__main__":
    main(*sys.argv[1:3])
